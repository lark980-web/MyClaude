/**
 * /init support: summarise a project into MYCLAUDE.md.
 *
 * Generated from facts on disk rather than by asking the model, for two
 * reasons: it works with no network, and it cannot invent build commands that
 * do not exist. The file is then loaded by loadMemory() and appended to the
 * system prompt, so the agent knows the layout without re-reading it every
 * session.
 */
import { readdirSync, readFileSync, existsSync } from "node:fs";
import { join, basename } from "node:path";

/** Directories that carry no useful signal for a project summary. */
const SKIP_DIRS = new Set([".git", "node_modules", "dist", "build", ".next", "target", "coverage", ".venv", "__pycache__", ".idea", ".vscode"]);

/** Collect a shallow picture of the repository. */
export function inspectProject(root) {
  const info = {
    name: basename(root),
    packageJson: null,
    topLevel: { dirs: [], files: [] },
    entryPoints: [],
    testFiles: 0,
    locales: [],
  };

  try {
    const pkgPath = join(root, "package.json");
    if (existsSync(pkgPath)) { info.packageJson = JSON.parse(readFileSync(pkgPath, "utf8")); }
  } catch {
    // A broken package.json should not abort the summary.
  }

  try {
    const entries = readdirSync(root, { withFileTypes: true });
    for (const e of entries) {
      if (e.name.startsWith(".")) { continue; }
      // Skip names that only exist because a shell variable failed to expand
      // ("%SystemDrive%", "$HOME"): they are debris, not project structure.
      if (/[%$]/.test(e.name)) { continue; }
      if (e.isDirectory()) {
        if (!SKIP_DIRS.has(e.name)) { info.topLevel.dirs.push(e.name); }
      } else {
        info.topLevel.files.push(e.name);
      }
    }
  } catch {
    // An unreadable root is not fatal.
  }

  // Two levels are enough to characterise a project without walking the
  // whole tree, which would be slow on a large repository.
  const seenExt = new Map();
  const walk = (dir, depth) => {
    if (depth > 2) { return; }
    let entries;
    try { entries = readdirSync(dir, { withFileTypes: true }); } catch { return; }
    for (const e of entries) {
      if (e.name.startsWith(".")) { continue; }
      const full = join(dir, e.name);
      if (e.isDirectory()) {
        if (!SKIP_DIRS.has(e.name)) { walk(full, depth + 1); }
      } else {
        const m = /\.([a-z0-9]+)$/i.exec(e.name);
        if (m) {
          const ext = m[1].toLowerCase();
          seenExt.set(ext, (seenExt.get(ext) || 0) + 1);
        }
        if (/\.(test|spec)\.[a-z]+$/i.test(e.name)) { info.testFiles++; }
      }
    }
  };
  walk(root, 0);
  info.locales = [...seenExt.entries()].sort((a, b) => b[1] - a[1]).slice(0, 6);

  // Common entry points, in the order package.json would declare them.
  const candidates = ["src/main.js", "src/index.js", "index.js", "main.js", "src/main.ts", "src/index.ts"];
  for (const c of candidates) {
    if (existsSync(join(root, c))) { info.entryPoints.push(c); }
  }

  return info;
}

/** Render the summary as Markdown for MYCLAUDE.md. */
export function renderProjectMemory(info) {
  const pkg = info.packageJson || {};
  const out = [];
  out.push("# " + (pkg.name || info.name));
  out.push("");
  if (pkg.description) { out.push(pkg.description); out.push(""); }
  out.push("> Generated by `/init`. Edit freely — the agent reads this on every start,");
  out.push("> and it is sent as part of the system prompt.");
  out.push("");

  if (info.entryPoints.length) {
    out.push("## Entry points");
    out.push("");
    for (const e of info.entryPoints) { out.push("- `" + e + "`"); }
    out.push("");
  }

  const dirs = info.topLevel.dirs.filter((d) => d !== "test" && d !== "tests").slice(0, 12);
  if (dirs.length) {
    out.push("## Layout");
    out.push("");
    for (const d of dirs) { out.push("- `" + d + "/`"); }
    out.push("");
  }

  const scripts = pkg.scripts || {};
  const scriptKeys = Object.keys(scripts);
  if (scriptKeys.length) {
    out.push("## Commands");
    out.push("");
    for (const k of scriptKeys.slice(0, 12)) {
      out.push("- `npm run " + k + "` — " + String(scripts[k]).slice(0, 100));
    }
    out.push("");
  }

  if (info.locales.length) {
    out.push("## Languages");
    out.push("");
    for (const pair of info.locales) { out.push("- ." + pair[0] + " (" + pair[1] + ")"); }
    out.push("");
  }

  if (info.testFiles) {
    out.push("## Tests");
    out.push("");
    out.push(info.testFiles + " test file(s). Run them before claiming a change works.");
    out.push("");
  }

  out.push("## Notes for the agent");
  out.push("");
  out.push("- Read the relevant files before editing; do not guess at contents.");
  out.push("- Match the existing style of the file you are changing.");
  out.push("- Run the test command after a behavioural change.");
  out.push("");
  return out.join("\n");
}

/** Markdown dump of a conversation, for /export. */
export function renderTranscriptMarkdown(agent, config) {
  const out = [];
  out.push("# Conversation export");
  out.push("");
  out.push("- model: `" + config.model + "`");
  out.push("- exported: " + new Date().toISOString());
  out.push("- messages: " + agent.messages.length);
  out.push("");
  out.push("---");
  out.push("");
  for (const m of agent.messages) {
    const role = m.role === "user" ? "User" : m.role === "assistant" ? "Assistant" : "Tool";
    let text = m.content;
    if (typeof text !== "string") {
      try { text = JSON.stringify(text, null, 2); } catch { text = String(text); }
    }
    if (!text) { continue; }
    out.push("## " + role);
    out.push("");
    out.push(String(text));
    out.push("");
  }
  return out.join("\n");
}
