import WebSocket from "ws";
const CDP = "http://127.0.0.1:9333";
const timeout = (ms) => new Promise((_, rej) => setTimeout(() => rej(new Error("timeout")), ms));
let list = await Promise.race([fetch(CDP + "/json/list").then(r => r.json()), timeout(8000)]);
let page = list.find((t) => t.type === "page");
if (!page) page = await (await fetch(CDP + "/json/new?about:blank", { method: "PUT" })).json();
const ws = new WebSocket(page.webSocketDebuggerUrl);
let id = 0; const pending = new Map();
ws.on("message", (raw) => { const m = JSON.parse(raw.toString()); if (m.id && pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id); } });
ws.on("error", (e) => console.log("ws-err:", String(e).slice(0, 80)));
const send = (method, params = {}) => { const i = ++id; const p = new Promise((res, rej) => { pending.set(i, res); setTimeout(() => rej(new Error("eval-timeout")), 10000); }); ws.send(JSON.stringify({ id: i, method, params })); return p; };
await Promise.race([new Promise((r) => ws.on("open", r)), timeout(8000)]);
await send("Runtime.enable"); await send("Page.enable");
await send("Emulation.setDeviceMetricsOverride", { width: 1400, height: 900, deviceScaleFactor: 2, mobile: false });
await send("Page.navigate", { url: "http://127.0.0.1:7788/" });
await new Promise((r) => setTimeout(r, 3500));
const evalJs = async (expr) => { const r = await send("Runtime.evaluate", { expression: expr, returnByValue: true }); return r.result?.result?.value ?? ("EXC: " + JSON.stringify(r.result?.exceptionDetails || "").slice(0, 150)); };
console.log("open:", await evalJs(`document.getElementById("app").classList.add("insp-open"); "opened"`));
console.log("click:", await evalJs(`document.getElementById("tab-insp-changes").click(); "clicked"`));
await new Promise((r) => setTimeout(r, 1500));
console.log("visible:", await evalJs(`(() => { const b = document.getElementById("changes-body"); return b && !b.hidden ? "shown, rows=" + b.querySelectorAll(".chg-file").length + " sum=" + (b.querySelector(".chg-sum")?.textContent || "(空)") : "NOT-SHOWN"; })()`));
ws.close(); process.exit(0);
